// --- AC-29: the manifest-less tree + ALL FOUR accounting channels -------------

// runWipeAccounting seeds the interrupted-first-copy state (payload
// under <dest>/<SET-ID>-001 with NO MANIFEST.json - the ownership
// table's "absent -> ours-by-namespace" row), then copies and asserts
// the channels for the requested report mode. The expected numbers are
// computed by the test's OWN walker over the tree BEFORE the copy, so
// the recorded figures are pinned exactly, not just non-zero.
func runWipeAccounting(t *testing.T, setID string, jsonMode bool) {
	t.Helper()
	cat := createCatalog(t)
	root := t.TempDir()
	writeFileP(t, filepath.Join(root, "real.txt"), pattern(6, 777), 0o644)
	scanBuildFixture(t, root, cat, setID)
	planSynthetic(t, cat, setID, copySyntheticUsable)
	dest := filepath.Join(t.TempDir(), "dest")
	imageRoot := destImageDir(dest, setID, 1)

	// THE INTERRUPTED FIRST COPY: a payload tree with no manifest (the
	// writer died before 6.6's manifest write). Three entries beyond
	// the root: files/, a file, and a subdir with its file.
	writeFileP(t, filepath.Join(imageRoot, "files", "stale-a.txt"), pattern(9, 1000), 0o644)
	writeFileP(t, filepath.Join(imageRoot, "files", "sub", "stale-b.bin"), pattern(8, 2500), 0o644)
	if _, err := os.Lstat(filepath.Join(imageRoot, media.ManifestFileName)); !os.IsNotExist(err) {
		t.Fatalf("the seeded first-copy tree must hold no manifest (err=%v)", err)
	}
	wantEntries, wantBytes := walkWipeTree(t, imageRoot)
	wantHuman := fmt.Sprintf("wiped: image 1: removed %d entries (%s) from %s before rewrite",
		wantEntries, units.FormatBytes(wantBytes), imageRoot)
	wantStderr := fmt.Sprintf("image 1: removed %d entries (%s) from %s before rewrite",
		wantEntries, units.FormatBytes(wantBytes), imageRoot)

	args := []string{"copy", "--catalog", cat, "--set-id", setID, "--dest", dest}
	if jsonMode {
		args = append(args, "--json")
	}
	stdout, stderr, code := runCopyChild(t, nil, args...)
	if code != report.ExitOK {
		t.Fatalf("wiping copy exit = %d, want 0\nstdout: %s\nstderr: %s", code, stdout, stderr)
	}

	// CHANNEL 1 (human leg): the line exists with the exact numbers,
	// positioned AFTER the totals line and as the last stdout line of
	// this clean run (the metadata/failure positions are pinned at the
	// byte level by TestWriteCopyReportWipeLinePosition).
	// CHANNEL 2 (json leg): the record carries the same numbers, and no
	// wipe prose may leak onto stdout (assertJSONModeStreams).
	if jsonMode {
		rep := parseCopyReport(t, stdout)
		if len(rep.Wipes) != 1 {
			t.Fatalf("wipes = %+v, want exactly one record", rep.Wipes)
		}
		w := rep.Wipes[0]
		if w.Image != 1 || w.Path != imageRoot || w.EntriesRemoved != wantEntries || w.BytesRemoved != wantBytes {
			t.Errorf("wipe record = %+v, want image 1 / %s / entries %d / bytes %d",
				w, imageRoot, wantEntries, wantBytes)
		}
		assertJSONModeStreams(t, stdout, stderr, wantStderr)
	} else {
		lines := nonEmptyLines(stdout)
		var wipedIdx = -1
		for i, line := range lines {
			if strings.HasPrefix(line, "wiped: ") {
				if wipedIdx >= 0 {
					t.Errorf("more than one wipe line on a single-wipe run:\n%s", stdout)
				}
				wipedIdx = i
			}
		}
		if wipedIdx < 0 {
			t.Fatalf("stdout lacks the wiped line:\n%s", stdout)
		}
		if lines[wipedIdx] != wantHuman {
			t.Errorf("wiped line = %q\nwant      %q", lines[wipedIdx], wantHuman)
		}
		var totalsIdx = -1
		for i, line := range lines {
			if strings.HasPrefix(line, "totals: ") {
				totalsIdx = i
			}
		}
		if totalsIdx < 0 || totalsIdx > wipedIdx {
			t.Errorf("the wiped line must sit AFTER the totals line (4.6.1 channel 1):\n%s", stdout)
		}
		if wipedIdx != len(lines)-1 {
			t.Errorf("the wiped line must be the last line of this clean run (before metadata/failure blocks):\n%s", stdout)
		}
	}

	// CHANNEL 3: the run_events row (level warn, relpath = the
	// destroyed path, detail with the counts, the path, and the
	// image/set identity).
	db := catOpen(t, cat)
	runID := newestRunID(t, db, "copy")
	var level, relpath, detail string
	if err := db.QueryRow(`SELECT level, relpath, detail FROM run_events
		WHERE run_id = ? AND detail LIKE 'wiped before rewrite:%'`, runID).
		Scan(&level, &relpath, &detail); err != nil {
		t.Fatalf("reading the wipe run_events row: %v", err)
	}
	wantDetail := fmt.Sprintf("wiped before rewrite: removed %d entries (%s) from %s (image 1 of set %s)",
		wantEntries, units.FormatBytes(wantBytes), imageRoot, setID)
	if level != "warn" || relpath != imageRoot || detail != wantDetail {
		t.Errorf("run_events row = (level %q, relpath %q, detail %q)\nwant (warn, %q, %q)",
			level, relpath, detail, imageRoot, wantDetail)
	}

	// CHANNEL 4: the live stderr line is the channel-1 message MINUS the
	// "wiped: " prefix (pinned for the json leg above; stderr carries it
	// in both modes).
	if !strings.Contains(stderr, wantStderr) {
		t.Errorf("stderr lacks the live wipe warning %q:\n%s", wantStderr, stderr)
	}
	if strings.Contains(stderr, "wiped: image") {
		t.Errorf("the stderr channel must not carry the stdout line's 'wiped: ' prefix:\n%s", stderr)
	}

	// AC-29's tail: the rewrite completes and the media verifies clean.
	if _, err := os.Lstat(filepath.Join(imageRoot, "files", "stale-a.txt")); !os.IsNotExist(err) {
		t.Errorf("the stale tree survived the wipe (err=%v)", err)
	}
	assertVerifyFullMatch(t, cat, setID, 1)
}

