	// marked, and present in the content list.
	for _, other := range []string{"a.txt", "sub/c.txt"} {
		if image, copied := fileState(t, cat, setID, other); image != int64(1) || copied != 1 {
			t.Errorf("surviving member %s = (image %v, copied %d), want (image 1, 1)", other, image, copied)
		}
	}
