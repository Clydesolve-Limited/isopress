	if rep.Skipped != 1 {
		t.Errorf("skipped = %d, want 1 (counted)", rep.Skipped)
	}
	if len(rep.Images) != 1 || rep.Images[0].Skipped != 1 {
		t.Errorf("image report = %+v, want the skip counted on the rewritten image", rep.Images)
	}
	// The warning names the member and the source-changed reason.
	for _, want := range []string{member, "source changed"} {
		if !strings.Contains(stderr, want) {
			t.Errorf("stderr lacks %q:\n%s", want, stderr)
		}
	}
	// ABSENT from the rewritten image's content list + copied stays 0.
	db := catOpen(t, cat)
