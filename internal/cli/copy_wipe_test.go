// runCopyBlockedAtItem starts a REAL copy child that parks at the N-th
// item's write (the 12.7 block seam), sends exactly one signal, and
// returns the child's stderr and exit code. It is the reusable shape of
// copy_test.go's runCopyInterruptedRunCase for tests that need THEIR
// fixture interrupted rather than the crash fixture's.
func runCopyBlockedAtItem(t *testing.T, sig syscall.Signal, hookAfter string, stdout *bytes.Buffer,
	args ...string) (stderrAll string, code int) {
	t.Helper()
	cmd := exec.Command(os.Args[0], args...)
	cmd.Env = append(append(os.Environ(), scanSignalHelperEnv+"=1"), copyHookEnv(hookAfter, "partial", "block")...)
	stderrPipe, err := cmd.StderrPipe()
	if err != nil {
		t.Fatal(err)
	}
	cmd.Stdout = stdout
	if err := cmd.Start(); err != nil {
		t.Fatal(err)
	}
	exited := false
	defer func() {
		if !exited {
			_ = cmd.Process.Kill()
			_ = cmd.Wait()
		}
	}()

	lineCh := make(chan string, 16)
	go func() {
		defer close(lineCh)
		buf := make([]byte, 1)
		var line []byte
		for {
			n, rerr := stderrPipe.Read(buf)
			if n > 0 {
				if buf[0] == '\n' {
					lineCh <- string(line)
					line = line[:0]
				} else {
					line = append(line, buf[0])
				}
			}
			if rerr != nil {
				if len(line) > 0 {
					lineCh <- string(line)
				}
				return
			}
		}
	}()

	var sb strings.Builder
	signaled := false
	deadline := time.After(2 * time.Minute)
interruptLoop:
	for {
		select {
		case line, ok := <-lineCh:
			if !ok {
				break interruptLoop
			}
			sb.WriteString(line)
			sb.WriteByte('\n')
			if !signaled && strings.Contains(line, "COPY-HOOK-REACHED") {
				signaled = true
				if err := cmd.Process.Signal(sig); err != nil {
					t.Errorf("%v to copy child: %v", sig, err)
					break interruptLoop
				}
			}
		case <-deadline:
			break interruptLoop
		}
	}
	if !signaled {
		t.Fatalf("never saw the mid-copy sentinel; stderr so far:\n%s", sb.String())
	}
	waitCh := make(chan error, 1)
	go func() { waitCh <- cmd.Wait() }()
	var waitErr error
	select {
	case waitErr = <-waitCh:
		exited = true
	case <-time.After(2 * time.Minute):
		t.Fatalf("copy child did not exit within 2 minutes of the %v (stderr: %s)", sig, sb.String())
	}
	for line := range lineCh {
		sb.WriteString(line)
		sb.WriteByte('\n')
	}
	exitErr, ok := waitErr.(*exec.ExitError)
	if !ok {
		t.Fatalf("copy child did not exit with an error after %v: %v (stderr: %s)", sig, waitErr, sb.String())
	}
	return sb.String(), exitErr.ExitCode()
}

